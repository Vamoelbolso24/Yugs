/**
 * Builds content/counter-names.json: official counter type -> name (e.g. 0x1 -> "Spell Counter").
 * EDOPro keeps counter names in its client strings, which we don't ship, so we work them out from the
 * card scripts (which counter code a card uses) plus the card's text (which "X Counter" it talks about).
 * Run again after updating vendor/CardScripts:  node scripts/gen-counter-names.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { CardDatabase } from '../src/engine/cardDb.ts';
import { CARD_DB_FILES } from '../src/paths.ts';

const root = path.resolve(import.meta.dirname, '..');
const scriptsDir = path.join(root, 'vendor/CardScripts');
const consts = new Map<string, number>();
for (const f of ['constant.lua', 'card_counter_constants.lua']) {
  for (const m of fs.readFileSync(path.join(scriptsDir, f), 'utf8').matchAll(/^(COUNTER_[A-Z0-9_]+)\s*=\s*(0x[0-9a-fA-F]+|\d+)/gm)) consts.set(m[1]!, Number(m[2]));
}
const cards = new CardDatabase(CARD_DB_FILES);
const votes = new Map<number, Map<string, number>>();
const val = (t: string) => (/^0x|^\d/.test(t) ? Number(t) : consts.get(t));
const files = fs.readdirSync(path.join(scriptsDir, 'official')).filter((f) => /^c\d+\.lua$/.test(f));
for (const f of files) {
  const src = fs.readFileSync(path.join(scriptsDir, 'official', f), 'utf8');
  const codes = new Set<number>();
  for (const m of src.matchAll(/counter_(?:place_)?list\s*=\s*\{([^}]*)\}/g))
    for (const t of m[1]!.split(',').map((x) => x.trim()).filter(Boolean)) { const v = val(t); if (v !== undefined) codes.add(v); }
  for (const m of src.matchAll(/AddCounter\(\s*(0x[0-9a-fA-F]+|COUNTER_[A-Z0-9_]+)/g)) { const v = val(m[1]!); if (v !== undefined) codes.add(v); }
  if (codes.size !== 1) continue;
  const card = cards.get(Number(f.slice(1, -4)));
  if (!card) continue;
  const names = new Set<string>();
  for (const m of card.desc.matchAll(/\b([A-Z][A-Za-z0-9'.]*(?:[ -][A-Z][A-Za-z0-9'.]*)?)[ -]Counters?\b/g)) {
    const n = m[1]!.replace(/^(?:Place|Remove|Each|All|The|A|An|Any|With|That|Those|Its|If|When|Put)\s+/, '');
    if (!/^(?:Place|Remove|Each|All|The|Any|With|That|Those|Its|If|When|Put|X)$/.test(n)) names.add(n);
  }
  if (names.size !== 1) continue;
  const code = [...codes][0]!; const name = [...names][0]!;
  const v = votes.get(code) ?? new Map<string, number>(); v.set(name, (v.get(name) ?? 0) + 1); votes.set(code, v);
}
const out: Record<string, string> = { _comment: 'Names of official counters, e.g. "0x1": "Spell" (shown as "Spell Counter"). Generated by scripts/gen-counter-names.ts from card scripts + texts; safe to edit. Custom counters go in content/custom/counters.json.' };
for (const [code, v] of [...votes].sort((a, b) => a[0] - b[0])) {
  const [name] = [...v].sort((a, b) => b[1] - a[1])[0]!;
  out['0x' + code.toString(16)] = name;   // "Spell" (the game adds " Counter")
}
fs.writeFileSync(path.join(root, 'content/counter-names.json'), JSON.stringify(out, null, 2) + '\n');
console.log(Object.keys(out).length - 1, 'counter names written');
