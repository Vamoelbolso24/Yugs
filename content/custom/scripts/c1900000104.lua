-- Abra
-- Once per turn (Quick Effect): You can pay 800 LP; banish this card until your next Standby Phase.
-- (Like Fly/Dig: a temporary banish, then Duel.ReturnToField at the right moment.)
local s,id=GetID()
function s.initial_effect(c)
	local e1=Effect.CreateEffect(c)
	e1:SetDescription(aux.Stringid(id,0))
	e1:SetCategory(CATEGORY_REMOVE)
	e1:SetType(EFFECT_TYPE_QUICK_O)
	e1:SetCode(EVENT_FREE_CHAIN)
	e1:SetRange(LOCATION_MZONE)
	e1:SetProperty(EFFECT_FLAG_DAMAGE_STEP)
	e1:SetHintTiming(0,TIMINGS_CHECK_MONSTER|TIMING_END_PHASE)
	e1:SetCountLimit(1)
	e1:SetCost(Cost.PayLP(800))
	e1:SetTarget(function(e,tp,eg,ep,ev,re,r,rp,chk)
		if chk==0 then return e:GetHandler():IsAbleToRemove() end
		Duel.SetOperationInfo(0,CATEGORY_REMOVE,e:GetHandler(),1,0,0)
	end)
	e1:SetOperation(s.operation)
	c:RegisterEffect(e1)
end
function s.operation(e,tp)
	local c=e:GetHandler()
	if not c:IsRelateToEffect(e) then return end
	if Duel.Remove(c,POS_FACEUP,REASON_EFFECT+REASON_TEMPORARY)==0 then return end
	c:RegisterFlagEffect(id,RESET_EVENT|RESETS_STANDARD,0,1)
	local turn=Duel.GetTurnCount()
	-- Back at YOUR next Standby Phase (not the one of this turn)
	local e1=Effect.CreateEffect(c)
	e1:SetType(EFFECT_TYPE_FIELD+EFFECT_TYPE_CONTINUOUS)
	e1:SetCode(EVENT_PHASE+PHASE_STANDBY)
	e1:SetCountLimit(1)
	e1:SetCondition(function() return Duel.IsTurnPlayer(tp) and Duel.GetTurnCount()~=turn and c:GetFlagEffect(id)>0 end)
	e1:SetOperation(function()
		c:ResetFlagEffect(id)
		Duel.ReturnToField(c)
	end)
	e1:SetReset(RESET_PHASE|PHASE_STANDBY|RESET_SELF_TURN,2)
	Duel.RegisterEffect(e1,tp)
end
